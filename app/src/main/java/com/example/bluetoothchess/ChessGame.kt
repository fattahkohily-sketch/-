# Bluetooth Chess

هذا المشروع هو نسخة أولية من لعبة شطرنج Android Native تشترك بين جهازين عبر البلوتوث دون إنترنت.

## الميزات الحالية
- لوحة شطرنج 8x8
- قطع الشطرنج الأساسية
- حركات pawns, rooks, bishops, knights, queen, king
- اتصال Bluetooth بين جهازين
- اختيار Host أو Join
- أذونات Bluetooth للأندرويد 12+

## التشغيل
1. افتح المشروع في Android Studio.
2. انتظر اكتمال Gradle Sync.
3. تأكد من اختيار JDK 17.
4. اضغط على Run.
5. شغّل التطبيق على هاتف أو محاكي.

## ملاحظات مهمة
- هذا مشروع أولي (prototype) مناسب للتطوير المستقبلي.
- في Android 12+ تحتاج صلاحيات البلوتوث لتشغيل الاتصال.
- الاتصال عبر البلوتوث يعتمد على الأجهزة المزدوجة المتوافقة مع معيار RFCOMM.

## بنية المشروع
- `MainActivity.kt` - شاشة اللعبة
- `ChessGame.kt` - منطق الشطرنج
- `BluetoothController.kt` - اتصال Bluetooth
- `activity_main.xml` - تصميم اللوحة والواجهة

## بناء APK
- من Android Studio: Build → Build APK(s)
- ثم ابحث عن الملف في:
  `app/build/outputs/apk/debug/app-debug.apk`

